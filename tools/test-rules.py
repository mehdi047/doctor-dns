ACL_ROWS = [{"ip": ip, "name": "u%d" % i, "up": 0, "down": 0, "total": 0}
            for i, ip in enumerate(["198.51.100.10", "198.51.100.20",
                                    "198.51.100.30"], 1)]


class R:
    def __init__(self, out, rc=0):
        self.stdout, self.returncode, self.stderr = out, rc, ""


def fake_run(*args):
    if args[:2] == (rules.NFT, "list"):
        return R(NFT_CHAIN)
    if args[:3] == (rules.NFT, "-j", "list"):
        return R(json.dumps({"nftables": [{"metainfo": {}}, {"set": {
            "name": args[-1], "elem": SETS.get(args[-1], [])}}]}))
    if args[0] == rules.ACL:
        return R(json.dumps(ACL_ROWS))
    if args[0] == "systemctl":
        return R("active\n")
    return None


rules.run = fake_run


def call(*argv):
    out = io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(out):
        rc = rules.main(list(argv))
    return rc, out.getvalue()


