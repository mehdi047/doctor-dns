# The firewall and systemd, as the relay would answer. prof_9 is a leftover
# set with no rule pointing at it - the kind found on the live relay.
NFT_CHAIN = ("table ip smartdns_nat {\n chain pre {\n"
             "  ip saddr @prof_2 udp dport 53 redirect to :%d\n"
             "  ip saddr @prof_2 tcp dport 53 redirect to :%d\n }\n}\n"
             % (prof_dns.port, prof_dns.port))
