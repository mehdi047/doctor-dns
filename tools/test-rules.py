# ------------------------------------------------------- stand-in resolvers
class FakeDNS:
    """Answers A queries from a table; silent=True answers nothing at all."""

    def __init__(self, table, silent=False):
        self.table, self.silent = table, silent
        self.sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        self.sock.bind(("127.0.0.1", 0))
        self.port = self.sock.getsockname()[1]
        threading.Thread(target=self.serve, daemon=True).start()

    def serve(self):
        while True:
            try:
                data, peer = self.sock.recvfrom(4096)
            except OSError:
                return
            if self.silent:
                continue
            off, labels = 12, []
            while data[off]:
                labels.append(data[off + 1:off + 1 + data[off]].decode())
                off += 1 + data[off]
            question = data[12:off + 5]
            ips = self.table.get(".".join(labels), [])
            reply = data[:2] + struct.pack(">HHHHH", 0x8180, 1, len(ips), 0, 0)
            reply += question
            for ip in ips:
                reply += struct.pack(">HHHIH", 0xC00C, 1, 1, 60, 4) + socket.inet_aton(ip)
            self.sock.sendto(reply, peer)


